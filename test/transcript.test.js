import assert from "node:assert/strict";
import test from "node:test";

import {
  buildCaptionUrlCandidates,
  buildTimedtextCandidates,
  decodeHtmlEntities,
  extractBalancedJson,
  extractPlayerResponse,
  orderTracksByPreference,
  parseCaptionPayload
} from "../transcript.js";

test("parseCaptionPayload extracts and decodes json3 caption text", () => {
  const raw = JSON.stringify({
    events: [
      { segs: [{ utf8: "Hello&nbsp;" }, { utf8: "world" }] },
      { segs: [{ utf8: "Focus &amp; execution" }] },
      { segs: [] },
      { other: "ignored" }
    ]
  });

  assert.equal(parseCaptionPayload(raw), "Hello world\nFocus & execution");
});

test("parseCaptionPayload extracts XML captions without browser DOM APIs", () => {
  const raw = [
    "<transcript>",
    '<text start="0" dur="2">First &amp; useful line</text>',
    "<p>Second &#39;quoted&#39; line</p>",
    "</transcript>"
  ].join("");

  assert.equal(parseCaptionPayload(raw), "First & useful line\nSecond 'quoted' line");
});

test("parseCaptionPayload strips VTT metadata and keeps cue text", () => {
  const raw = [
    "WEBVTT",
    "",
    "NOTE generated by YouTube",
    "1",
    "00:00:00.000 --> 00:00:02.000",
    "First caption line",
    "",
    "2",
    "00:00:02.000 --> 00:00:04.000",
    "Second caption line"
  ].join("\n");

  assert.equal(parseCaptionPayload(raw), "First caption line Second caption line");
});

test("orderTracksByPreference prefers English, then English variants, then other tracks", () => {
  const ordered = orderTracksByPreference([
    { languageCode: "pl", baseUrl: "pl" },
    { languageCode: "en-GB", baseUrl: "en-gb" },
    { languageCode: "de", baseUrl: "de" },
    { languageCode: "en", baseUrl: "en" }
  ]);

  assert.deepEqual(
    ordered.map((track) => track.baseUrl),
    ["en", "en-gb", "pl", "de"]
  );
});

test("caption URL candidates include original, json3, and vtt variants", () => {
  const candidates = buildCaptionUrlCandidates("https://example.com/captions?lang=en");

  assert.equal(candidates.length, 3);
  assert.equal(candidates[0], "https://example.com/captions?lang=en");
  assert.equal(new URL(candidates[1]).searchParams.get("fmt"), "json3");
  assert.equal(new URL(candidates[2]).searchParams.get("fmt"), "vtt");
});

test("timedtext fallback candidates preserve track metadata and add asr fallback", () => {
  const candidates = buildTimedtextCandidates("video-123", {
    languageCode: "en",
    name: { runs: [{ text: "English" }, { text: " auto" }] },
    kind: "manual",
    vssId: ".en"
  });

  assert.ok(candidates.length >= 5);

  const first = new URL(candidates[0]);
  assert.equal(first.hostname, "www.youtube.com");
  assert.equal(first.pathname, "/api/timedtext");
  assert.equal(first.searchParams.get("v"), "video-123");
  assert.equal(first.searchParams.get("lang"), "en");
  assert.equal(first.searchParams.get("name"), "English auto");
  assert.equal(first.searchParams.get("kind"), "manual");

  assert.ok(candidates.some((url) => new URL(url).searchParams.get("fmt") === "json3"));
  assert.ok(candidates.some((url) => new URL(url).searchParams.get("fmt") === "vtt"));
  assert.ok(candidates.some((url) => new URL(url).searchParams.get("kind") === "asr"));
});

test("extractPlayerResponse handles balanced braces inside strings", () => {
  const html =
    '<script>ytInitialPlayerResponse = {"videoDetails":{"title":"Brace } in title"},"captions":{"x":1}};</script>';

  assert.deepEqual(extractPlayerResponse(html), {
    videoDetails: { title: "Brace } in title" },
    captions: { x: 1 }
  });
});

test("extractBalancedJson throws for incomplete JSON objects", () => {
  assert.throws(() => extractBalancedJson('prefix {"a": 1', 7), /Could not parse/);
});

test("decodeHtmlEntities supports named, decimal, and hex entities in Node", () => {
  assert.equal(decodeHtmlEntities("A &amp; B &#39;C&#39; &#x1f680;"), "A & B 'C' 🚀");
});

test("decodeHtmlEntities keeps invalid numeric entities unchanged", () => {
  assert.equal(decodeHtmlEntities("bad &#999999999999; entity"), "bad &#999999999999; entity");
});
